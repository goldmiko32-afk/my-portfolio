// ========================================
// ТЕКУЩИЙ СЛАЙД
// ========================================

let currentCategory = "";
let currentSlide = 0;


// ========================================
// ОТКРЫТИЕ
// ========================================

function openModal(category) {

    if (!slides[category]) {
        return;
    }

    currentCategory = category;
    currentSlide = 0;

    const modal = document.getElementById("infoModal");

    modal.classList.add("active");

    document.body.style.overflow = "hidden";

    updateSlide();
}


// ========================================
// ЗАКРЫТИЕ
// ========================================

function closeModal() {

    const modal = document.getElementById("infoModal");

    modal.classList.remove("active");

    document.body.style.overflow = "";
}


// ========================================
// ОБНОВЛЕНИЕ СЛАЙДА
// ========================================

function updateSlide() {

    const data = slides[currentCategory][currentSlide];

    if (!data) {
        return;
    }

    document.getElementById("modalIcon").textContent =
        data.icon;

    document.getElementById("modalTitle").textContent =
        data.title;

    document.getElementById("modalText").textContent =
        data.text;

    document.getElementById("slideNumber").textContent =
        String(currentSlide + 1).padStart(2, "0") +
        " / " +
        String(slides[currentCategory].length).padStart(2, "0");


    createDots();
}


// ========================================
// ТОЧКИ СЛАЙДОВ
// ========================================

function createDots() {

    const dotsContainer =
        document.getElementById("slideDots");

    dotsContainer.innerHTML = "";

    slides[currentCategory].forEach(
        function (_, index) {

            const dot =
                document.createElement("span");

            dot.classList.add("dot");

            if (index === currentSlide) {
                dot.classList.add("active");
            }

            dotsContainer.appendChild(dot);
        }
    );
}


// ========================================
// СЛЕДУЮЩИЙ СЛАЙД
// ========================================

function nextSlide() {

    if (!slides[currentCategory]) {
        return;
    }

    currentSlide++;

    if (
        currentSlide >=
        slides[currentCategory].length
    ) {
        currentSlide = 0;
    }

    updateSlide();
}


// ========================================
// ПРЕДЫДУЩИЙ СЛАЙД
// ========================================

function previousSlide() {

    if (!slides[currentCategory]) {
        return;
    }

    currentSlide--;

    if (currentSlide < 0) {

        currentSlide =
            slides[currentCategory].length - 1;
    }

    updateSlide();
}


// ========================================
// КЛИК ВНЕ ОКНА
// ========================================

window.addEventListener(
    "click",
    function (event) {

        const modal =
            document.getElementById("infoModal");

        if (event.target === modal) {
            closeModal();
        }
    }
);


// ========================================
// КЛАВИАТУРА
// ========================================

document.addEventListener(
    "keydown",
    function (event) {

        const modal =
            document.getElementById("infoModal");

        if (!modal.classList.contains("active")) {
            return;
        }

        if (event.key === "Escape") {
            closeModal();
        }

        if (event.key === "ArrowRight") {
            nextSlide();
        }

        if (event.key === "ArrowLeft") {
            previousSlide();
        }
    }
);